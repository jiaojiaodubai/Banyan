// Copy the shared style linter bundle from the toolchain into the addon assets.
//
// The style editor runtime cannot import `node_modules`: it writes a small,
// self-contained set of files into <Zotero-data-dir>/banyan and runs the user's
// ESLint there. The toolchain produces one ESM bundle plus a metadata file; both
// are copied verbatim so the shipped linter stays traceable to a toolchain
// revision and schema revision. `--check` is used by `pnpm lint:check` so a
// dependency bump cannot silently leave the shipped linter behind.

import { createHash } from "node:crypto";
import { readFile, writeFile } from "node:fs/promises";
import { createRequire } from "node:module";
import path from "node:path";
import { fileURLToPath } from "node:url";
import prettier from "prettier";

const rootDir = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const outputDir = path.join(rootDir, "addon", "content", "styleEditor");
const checkOnly = process.argv.includes("--check");

const BUNDLE_ASSET = {
  source: "dist/eslint-plugin-banyan-style.mjs",
  target: "eslint-plugin-banyan-style.mjs",
};
const METADATA_ASSET = {
  source: "dist/build-metadata.json",
  target: "eslint-plugin-banyan-style.build.json",
};

function formatError(error) {
  return error instanceof Error ? error.message : String(error);
}

async function resolvePackage() {
  const require = createRequire(import.meta.url);
  let packageJSONPath;
  try {
    packageJSONPath = require.resolve("eslint-plugin-banyan-style/package.json");
  } catch (error) {
    throw new Error(
      `Cannot resolve eslint-plugin-banyan-style. Run \`pnpm install\` first. ${formatError(error)}`,
    );
  }

  const packageJSON = JSON.parse(await readFile(packageJSONPath, "utf8"));
  return {
    version: String(packageJSON.version ?? "0.0.0"),
    directory: path.dirname(packageJSONPath),
  };
}

function managedHeader(version, metadata) {
  return [
    `// Generated from eslint-plugin-banyan-style@${version}.`,
    `// Contract schema revision: ${metadata.schemaRevision}.`,
    "// Edit the toolchain package and run `pnpm gen:style-lint`; do not edit this file.",
    "",
  ].join("\n");
}

async function renderBundle(packageDir, version, metadata) {
  const sourcePath = path.join(packageDir, BUNDLE_ASSET.source);
  const targetPath = path.join(outputDir, BUNDLE_ASSET.target);
  const source = await readFile(sourcePath, "utf8");
  const config = (await prettier.resolveConfig(targetPath)) ?? {};
  const content = await prettier.format(
    managedHeader(version, metadata) + source,
    { ...config, filepath: targetPath },
  );
  return {
    targetPath,
    content,
    bundleSha256: createHash("sha256").update(content).digest("hex"),
  };
}

async function main() {
  const pkg = await resolvePackage();
  const metadata = JSON.parse(
    await readFile(path.join(pkg.directory, METADATA_ASSET.source), "utf8"),
  );
  const bundle = await renderBundle(pkg.directory, pkg.version, metadata);
  const metadataContent = `${JSON.stringify(
    {
      ...metadata,
      generator: "Banyan scripts/genStyleLint.mjs",
      bundleSha256: bundle.bundleSha256,
    },
    null,
    2,
  )}\n`;

  const rendered = [
    { targetPath: bundle.targetPath, content: bundle.content },
    {
      targetPath: path.join(outputDir, METADATA_ASSET.target),
      content: metadataContent,
    },
  ];

  let stale = 0;
  for (const { targetPath, content } of rendered) {
    const existing = await readFile(targetPath, "utf8").catch(() => "");
    if (existing === content) {
      console.log(`up to date: ${path.relative(rootDir, targetPath)}`);
      continue;
    }

    if (checkOnly) {
      stale += 1;
      console.error(`out of date: ${path.relative(rootDir, targetPath)}`);
      continue;
    }

    await writeFile(targetPath, content, "utf8");
    console.log(`updated: ${path.relative(rootDir, targetPath)}`);
  }

  if (stale) {
    console.error(
      "Style lint assets are out of date. Run `pnpm gen:style-lint` and commit the result.",
    );
    process.exitCode = 1;
  }
}

await main();
